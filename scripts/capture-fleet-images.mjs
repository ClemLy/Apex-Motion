/**
 * Real 2D renders of every Studio car, captured from the dev-only
 * /silhouette-capture route (app/silhouette-capture/) via Playwright — one
 * car per page load, so only a single live WebGL context exists at a time
 * (several concurrent contexts on one page proved unreliable: some silently
 * never finished rendering under GPU contention).
 *
 * Requires `npm run dev` running in another terminal first — this script
 * only drives a browser against it, it doesn't start the server itself
 * (starting/stopping Next reliably from inside a script is more fragile
 * than just asking for it to already be up, and this only runs by hand).
 *
 * Run with `npm run capture:fleet`. Output (public/silhouettes/*.png,
 * lib/three/silhouetteImages.ts) is committed, like optimize-models.mjs's.
 */
import { chromium } from "playwright";
import { createHash } from "node:crypto";
import { mkdir, readdir, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

/** Same order as lib/three/carConfigs.ts's CARS. */
const CAR_IDS = [
  "917k-lm",
  "930-turbo",
  "918-spyder",
  "911-carrera-4s",
  "718-gt4",
  "mission-r",
  "gt3rs",
];

const BASE_URL = "http://localhost:3000/silhouette-capture";
const OUTPUT_DIR = "public/silhouettes";
const MANIFEST_PATH = "lib/three/silhouetteImages.ts";
const READY_TIMEOUT_MS = 60000;

async function captureOne(page, id) {
  await page.goto(`${BASE_URL}?car=${id}`, { waitUntil: "networkidle" });
  await page.waitForFunction(
    () => document.body.dataset.captureReady === "true",
    { timeout: READY_TIMEOUT_MS },
  );
  return page.evaluate(() => {
    // Scoped, not a bare "canvas" selector: FluidBackground mounts its own
    // canvas globally in the root layout, on every route including this one.
    const canvas = document.querySelector("[data-capture-canvas] canvas");
    return canvas?.toDataURL("image/png") ?? null;
  });
}

async function main() {
  await mkdir(OUTPUT_DIR, { recursive: true });

  const browser = await chromium.launch();
  const page = await browser.newPage({
    viewport: { width: 1400, height: 420 },
  });

  const manifestEntries = [];

  for (const id of CAR_IDS) {
    process.stdout.write(`${id}... `);
    const dataUrl = await captureOne(page, id);
    if (!dataUrl) {
      console.log("no canvas found, skipped");
      continue;
    }

    const base64 = dataUrl.replace(/^data:image\/png;base64,/, "");
    const pngBuffer = Buffer.from(base64, "base64");
    const webpBuffer = await sharp(pngBuffer).webp({ quality: 85 }).toBuffer();
    const hash = createHash("sha256")
      .update(webpBuffer)
      .digest("hex")
      .slice(0, 8);
    const filename = `${id}.${hash}.webp`;
    await writeFile(path.join(OUTPUT_DIR, filename), webpBuffer);
    manifestEntries.push({ id, filename });
    console.log(
      `${filename} (${(webpBuffer.length / 1024).toFixed(0)}kb, was ${(pngBuffer.length / 1024).toFixed(0)}kb PNG)`,
    );
  }

  await browser.close();

  // Remove stale images from a previous run that no longer match any car.
  const keep = new Set(manifestEntries.map((e) => e.filename));
  for (const existing of await readdir(OUTPUT_DIR)) {
    if (!keep.has(existing)) await unlink(path.join(OUTPUT_DIR, existing));
  }

  const body = manifestEntries
    .map((e) => `  "${e.id}": "/silhouettes/${e.filename}",`)
    .join("\n");

  await writeFile(
    MANIFEST_PATH,
    `// Generated by scripts/capture-fleet-images.mjs — do not edit by hand.
export const SILHOUETTE_IMAGES: Record<string, string> = {
${body}
};
`,
  );
  console.log(`\nWrote ${MANIFEST_PATH}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
